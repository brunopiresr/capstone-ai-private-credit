def test_suite_covers_lesson_categories_and_each_supported_topic():
    cases = read_scenarios(SUITE / "scenarios.csv")
    assert len(cases) == 60
    assert Counter(c.category for c in cases) == {
        "happy_path": 18,
        "varied_phrasing": 12,
        "edge_case": 12,
        "out_of_scope": 6,
        "breaking": 12,
    }
    happy = Counter(c.topic for c in cases if c.category == "happy_path")
    varied = Counter(c.topic for c in cases if c.category == "varied_phrasing")
    assert len(happy) == 6 and set(happy.values()) == {3}
    assert varied == {topic: 2 for topic in happy}
    for topic in happy:
        assert {c.phrasing for c in cases if c.topic == topic} >= {
            "direct",
            "vague",
            "wrong_terminology",
        }


def test_duplicate_csv_ids_are_rejected(tmp_path):
    with (SUITE / "scenarios.csv").open(newline="") as file:
        reader = csv.DictReader(file)
        row, headers = next(reader), reader.fieldnames
    path = tmp_path / "duplicate.csv"
    with path.open("w", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=headers)
        writer.writeheader()
        writer.writerows([row, row])
    with pytest.raises(ValueError, match="unique"):
        read_scenarios(path)


def test_judge_cannot_hide_execution_or_contract_failures():
    answer = AgentAnswer(answer="A completed but incorrect answer")
    assert verdict(None, [], {"label": "pass"}) == "execution_error"
    assert verdict(answer, [{"passed": False}], {"label": "pass"}) == "fail"
    assert verdict(answer, [{"passed": True}], {"label": None}) == "needs_review"
    assert verdict(answer, [], {"label": "insufficient_evidence"}) == "needs_review"
    assert verdict(answer, [], {"label": "fail"}) == "fail"
    assert verdict(answer, [], {"label": "pass"}) == "pass"
    incomplete = answer.model_copy(update={"complete": False})
    assert verdict(incomplete, [], {"label": "pass"}) == "execution_error"


