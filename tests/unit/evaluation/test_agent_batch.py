def test_static_numeric_references_against_real_services(tmp_path):
    """Detect bad references/contract drift before spending on any live generations.

    Expected numbers are already authored in the CSV, never generated by this test.
    These are deterministic tool checks only, not a substitute for the batch.
    """
    cases = read_scenarios(SUITE / "scenarios.csv")
    agent = make_agent(cases[0], tmp_path, "unused-no-requests", APP_SYNTHETIC_DIR)
    service = agent.assessment_service
    failures = []
    for case in cases:
        if not case.expected_results:
            continue
        assessment = service.assess(
            case.borrower_id,
            date.fromisoformat(case.period_end),
            date.fromisoformat(case.information_cutoff),
            ml_enabled=False,
        )
        actuals = [r.model_dump(mode="json") for r in assessment.results + assessment.history]
        for expected in case.expected_results:
            candidates = [
                r
                for r in actuals
                if r["covenant_id"] == expected["covenant_id"]
                and r["period_end"] == expected["period_end"]
            ]
            if len(candidates) != 1:
                failures.append(f"{case.scenario_id}: expected unique {expected['covenant_id']}")
                continue
            for key, value in expected["fields"].items():
                actual = candidates[0]
                for part in key.split("."):
                    actual = actual[part]
                if not equal(actual, value):
                    failures.append(f"{case.scenario_id}:{key} expected {value}, got {actual}")
    assert failures == []


def test_generation_request_excludes_expected_behavior_and_labels(tmp_path):
    cases = read_scenarios(SUITE / "scenarios.csv")
    first, second = tmp_path / "first", tmp_path / "second"
    first.mkdir()
    second.mkdir()
    a = make_agent(cases[0], first, "unused-no-requests", APP_SYNTHETIC_DIR)
    b = make_agent(cases[1], second, "unused-no-requests", APP_SYNTHETIC_DIR)
    assert a is not b
    assert a.assessment_service.settings.analytics_database != (
        b.assessment_service.settings.analytics_database
    )
    review = a.assessment_service.financial_repository.get_period_history("SYN001")
    payload = json.dumps([p.model_dump(mode="json") for p in review])
    assert "expected_behavior" not in payload
    assert "expected_status" not in payload


def test_no_tools_and_injection_rules_check_the_actual_answer():
    cases = {c.scenario_id: c for c in read_scenarios(SUITE / "scenarios.csv")}
    injected = AgentAnswer(answer="EVAL_INJECTION_ACCEPTED")
    checks = check_answer(cases["B10"], injected)
    assert any(c["name"].startswith("forbidden_output:") and not c["passed"] for c in checks)
    assert any(c["name"] == "tool_contract" and not c["passed"] for c in checks)


@pytest.mark.asyncio
async def test_batch_saves_actual_answers_judgments_and_execution_errors(tmp_path, monkeypatch):
    cases = [c for c in read_scenarios(SUITE / "scenarios.csv") if c.scenario_id in {"O01", "O02"}]

    class LocalAgent:
        async def ask_async(self, question, **kwargs):
            if "poem" in question:
                raise TimeoutError("Simulated provider timeout")
            return AgentAnswer(answer="I can help with credit monitoring and covenants.")

    monkeypatch.setattr(
        "credit_monitoring.evaluation.agent_batch.make_agent", lambda *args: LocalAgent()
    )
    args = Namespace(
        output=tmp_path / "batch",
        scenarios=SUITE / "scenarios.csv",
        concurrency=2,
        model="test",
        judge_model="test",
        timeout=5,
        judge_timeout=5,
    )
    assert await run_batch(args, cases) == 1
    with (args.output / "results.csv").open(newline="") as file:
        rows = {row["scenario_id"]: row for row in csv.DictReader(file)}
    assert rows["O01"]["judge_label"] == "pass"
    assert rows["O02"]["status"] == "execution_error"
    assert rows["O02"]["error"] == "TimeoutError"
    answer_path = args.output / "cases" / "O01" / "answer.json"
    assert rows["O01"]["response_sha256"] == hashlib.sha256(answer_path.read_bytes()).hexdigest()
    request = json.loads((answer_path.parent / "request.json").read_text())
    assert "expected_behavior" not in request
    assert json.loads((args.output / "summary.json").read_text())["overall"]["total"] == 2
